// Generates experience/suspension-v2/vehicle-architectures.mjs: for each library vehicle, its name, the
// suspension ARCHITECTURE codes and wheelbase / CG height with their evidence level. No hardpoints: ESS has none.
// Run: node _build/suspension-v2/vehicle-architectures.mjs
import { writeFileSync } from 'node:fs';
import { vehicles, browseIds } from '../../experience/vehicles.mjs';
const rows = [];
for (const id of browseIds) {
  const v = vehicles[id], d = v.data;
  const f = d.archFront?.[0], r = d.archRear?.[0];
  if (!f && !r) continue;
  const num = k => Number.isFinite(d[k]?.[0]) ? [d[k][0], d[k][1]] : null;
  rows.push([id, v.name, f ?? null, r ?? null, num('wheelbase'), num('cg')]);
}
writeFileSync(new URL('../../experience/suspension-v2/vehicle-architectures.mjs', import.meta.url),
  '// Generated by _build/suspension-v2/vehicle-architectures.mjs. [id, name, front code, rear code, [wheelbase in, evidence], [CG in, evidence]]\n' +
  'export const vehicleArchitectures = ' + JSON.stringify(rows) + ';\n');
console.log(rows.length, 'vehicles');
