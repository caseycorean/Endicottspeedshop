"""Project the ESS reference dataset into browser-ready vehicle records."""
import argparse
import csv
import json
from pathlib import Path

FIELDS = {
    "weight": ("mass", "curb_weight", "as_tested_weight"),
    "front": ("mass", "front_share"),
    "cg": ("mass", "cg_height"),
    "wheelbase": ("geometry", "wheelbase"),
    "frontTrack": ("geometry", "track_front"),
    "rearTrack": ("geometry", "track_rear"),
    "hp": ("powertrain", "peak_power"),
    "hpRpm": ("powertrain", "peak_power_rpm"),
    "torque": ("powertrain", "peak_torque"),
    "torqueRpm": ("powertrain", "peak_torque_rpm", "peak_torque_rpm_min"),
    "redline": ("powertrain", "redline"),
    "gears": ("powertrain", "gear_ratios"),
    "finalDrive": ("powertrain", "final_drive"),
    "tire": ("tires_wheels", "tire_size_rear"),
    "frontTire": ("tires_wheels", "tire_size_front"),
    "frontSpring": ("suspension", "spring_rate_front"),
    "rearSpring": ("suspension", "spring_rate_rear"),
    "frontMotion": ("suspension", "motion_ratio_front"),
    "rearMotion": ("suspension", "motion_ratio_rear"),
    "cda": ("aero", "cda"),
    "test60": ("performance_validation", "zero_to_60"),
    "testEt": ("performance_validation", "quarter_mile_et"),
    "testTrap": ("performance_validation", "quarter_mile_trap"),
}

def field_value(row, group, names):
    for key in names:
        entry = row.get(group, {}).get(key, {})
        if entry.get("value") is not None:
            conditions = " ".join(entry.get(k) or "" for k in ("conditions", "note")).strip()
            if key == "peak_torque_rpm_min":
                conditions = f"Lower end of published torque plateau. {conditions}"
            return [entry["value"], entry["evidence"], entry.get("source"), conditions or None]
    return None

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="JSON with vehicles and sources arrays")
    parser.add_argument("crosswalk", type=Path, help="Recovered Supercar X source links")
    parser.add_argument("target", type=Path)
    args = parser.parse_args()
    package = json.loads(args.source.read_text())
    sources = {src["id"]: [src["title"], src.get("url")] for src in package["sources"]}
    links = {}
    with args.crosswalk.open() as stream:
        for related in csv.DictReader(stream):
            if related["legacy_class"] in ("Cars of Interest / Stock", "Benchmarks / Sport coupe/sedan") and related["capture"].startswith("https://web.archive.org/"):
                links.setdefault(related["config_id"], []).append([related["legacy_title"], related["capture"], related["match"]])
    records = {}
    for row in package["vehicles"]:
        identity = row["identity"]
        projected = {key: value for key, (group, *names) in FIELDS.items()
                     if (value := field_value(row, group, names)) is not None}
        if identity.get("body") and any(kind in identity["body"].lower() for kind in ("truck", "cab", "pickup")):
            category = "Pickup / truck"
        elif "hatchback" in identity.get("body", "").lower() and identity["layout"] in ("FF", "AWD"):
            category = "Hot hatch"
        elif any(kind in identity.get("body", "").lower() for kind in ("convertible", "soft-top", "roadster")):
            category = "Roadster / convertible"
        elif "sedan" in identity.get("body", "").lower():
            category = "Sedan"
        else:
            category = "Coupe / performance car"
        records[row["config_id"]] = {
            "name": row["display_name"], "make": identity["make"], "generation": identity["generation"],
            "body": identity["body"], "category": category, "layout": identity["layout"],
            "transmission": identity.get("transmission"), "fields": projected, "history": links.get(row["config_id"], []),
        }
    dump = lambda values: ",\n".join(
        f"  {json.dumps(key, ensure_ascii=False)}: {json.dumps(value, ensure_ascii=False, separators=(',', ':'))}"
        for key, value in values.items()
    )
    args.target.write_text("// Generated by _build/experience/build-catalog.py. Data-only source projection.\n"
                           + "export const catalog = {\n" + dump(records) + "\n};\n"
                           + "export const sources = {\n" + dump(sources) + "\n};\n")
